<details class="wp-block-details"><summary>Como funciona a associação Nautic Squad?</summary><!-- wp:paragraph -->
<p>Como um ginásio, mas na água — e para onde pode convidar família e amigos. Paga uma taxa mensal, usa o barco, limpa quando terminar e sai, sem as responsabilidades de propriedade, manutenção e administrativas. Há um sistema de agendamento online e de check-in e check-out eletrónico.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Qual o custo?</summary><!-- wp:paragraph -->
<p>Depende do tamanho do barco e do tipo de associação — mas muito menos do que possa imaginar! Peça uma visita para analisar as alternativas.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quantos sócios utilizam o barco?</summary><!-- wp:paragraph -->
<p>Varia consoante os níveis de associação. Para assegurar disponibilidade e exclusividade, o clube limita o número de sócios — o usual são 8 por embarcação.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Posso experimentar o veleiro?</summary><!-- wp:paragraph -->
<p>Claro! Basta ligar para agendar uma visita.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Qual a duração do contrato?</summary><!-- wp:paragraph -->
<p>Os contratos têm a duração de 12 meses.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Há taxas de manutenção não incluídas?</summary><!-- wp:paragraph -->
<p>Não. Mas se perder um equipamento ou danificar a embarcação, paga a substituição ou reparação até à franquia do seguro.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Duas pessoas podem partilhar o mesmo barco?</summary><!-- wp:paragraph -->
<p>Sim, com a associação Team. Em qualquer momento, pelo menos um dos sócios deve estar a bordo; não é permitida a cedência do barco a terceiros.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Posso passar a noite no veleiro?</summary><!-- wp:paragraph -->
<p>Sim, desde que reserve o período da noite, das 19h às 8h do dia seguinte.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Posso usar para além da minha quota?</summary><!-- wp:paragraph -->
<p>Sim. Cada sócio tem direito a utilização ilimitada desde que o barco esteja disponível — reservas a partir de 24 horas antes, sem custo adicional.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quais são os requisitos para ser sócio?</summary><!-- wp:paragraph -->
<p>Carta de navegação de Patrão Local e um curso de navegação ou experiência equivalente a RYA Day Skipper.</p>
